def render_chart_or_table(data, color=GOLD, height=320, key=None):
    """Render a bar chart with an explicit, always-visible Chart/Table
    toggle above it, rather than relying on the chart's own hover toolbar.

    Altair/Vega charts in Streamlit already have a built-in "Show data"
    icon that swaps the chart for a plain table — but that toolbar only
    appears on mouse hover, and once you're looking at the table there's
    nothing on screen to show a "Show chart" option exists until you hover
    over the table again. That's easy to miss, which is exactly what made
    it look like there was no way back. This gives the same choice through
    a plain, permanently visible control instead."""
    view = st.radio(
        "View as",
        ["Chart", "Table"],
        horizontal=True,
        key=f"view_toggle_{key}" if key else None,
        label_visibility="collapsed",
    )
    if view == "Table":
        table_df = data.reset_index()
        table_df.columns = ["Category", "Amount"]
        st.dataframe(table_df, hide_index=True, width="stretch")
    else:
        render_bar_chart(data, color=color, height=height)


